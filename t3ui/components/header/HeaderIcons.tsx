/**
 * One lucide mark by file name, at `size` points. Everything is read inside the JSX so a row that
 * keeps this element while its `name` changes (a recycled list row) shows the new mark.
 */
export function HIcon(props: { name: string; size?: number; tint?: string }) {
  return (
    <>
      {ICONS[props.name] === undefined
        ? <Icon name={props.name} size={props.size ?? 16} tint={props.tint} />
        : <Image
          src={ICONS[props.name]}
          fadeDuration={0}
          style={props.tint ? { width: props.size ?? 16, height: props.size ?? 16, tintColor: props.tint } : { width: props.size ?? 16, height: props.size ?? 16 }}
        />}
    </>
  );
}

