#!/usr/bin/env python3
"""Emit t3ui/themePreviews.ts: the theme picker's cards.

Reads packages/shared/src/themePalettes.ts (the built-in themes) and
themePreview.ts (the standard T3 Code preview colours) from the web checkout
and writes, per theme and mode, the seven roles ThemePreviewCircles.tsx paints
(sidebar, canvas, surface, accentSurface, accent, messageSurface,
messageAction) as hex. oklch values are converted the same way
apply_ocean_theme.py does. Usage:

  python3 tools/gen_theme_previews.py ../t3code/packages/shared/src > t3ui/themePreviews.ts

With `--palette-data PATH` it also writes t3ui/themePaletteData.ts: every role (THEME_COLOR_ROLES) of the
standard T3 Code palette and of each built-in theme (with its dark variant), as hex, for the theme editor and
the VS Code importer, which derive and default whole palettes in the app (themePalette.ts of the web).
"""
import json
import math
import re
import sys
from pathlib import Path

_ARGS = [a for a in sys.argv[1:]]
PALETTE_DATA = None
if "--palette-data" in _ARGS:
    _at = _ARGS.index("--palette-data")
    PALETTE_DATA = Path(_ARGS[_at + 1])
    del _ARGS[_at:_at + 2]
SRC = Path(_ARGS[0] if _ARGS else "../t3code/packages/shared/src")
ROLES = ["sidebar", "canvas", "surface", "accentSurface", "accent", "messageSurface", "messageAction"]


def to_hex(value: str) -> str:
    value = value.strip()
    if value.startswith("#"):
        return value.lower()
    m = re.fullmatch(r"oklch\(([\d.]+) ([\d.]+) ([\d.]+)\)", value)
    if not m:
        raise ValueError(f"unsupported colour {value}")
    lightness, chroma, hue = map(float, m.groups())
    a = chroma * math.cos(math.radians(hue))
    b = chroma * math.sin(math.radians(hue))
    l = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    mm = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    lin = (
        4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s,
        -1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s,
        -0.0041960863 * l - 0.7034186147 * mm + 1.7076147010 * s,
    )

    def enc(c: float) -> int:
        c = max(0.0, min(1.0, c))
        return round(255 * (12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055))

    return "#%02x%02x%02x" % tuple(enc(c) for c in lin)


def block(text: str, start: int) -> str:
    i = text.index("{", start)
    depth = 0
    for j in range(i, len(text)):
        depth += (text[j] == "{") - (text[j] == "}")
        if depth == 0:
            return text[i + 1 : j]
    raise ValueError("unclosed block")


def roles_of(body: str) -> dict:
    found = dict(re.findall(r'^\s*(\w+):\s*"([^"]+)"', body, re.M))
    return {r: to_hex(found[r]) for r in ROLES}


def role_list(palettes: str) -> list:
    start = palettes.index("export const THEME_COLOR_ROLES")
    return re.findall(r'"(\w+)"', palettes[start:palettes.index("] as const", start)])


def full_hex(value: str) -> str:
    """#rrggbb or #rrggbbaa for a palette colour (hex or oklch with an optional alpha)."""
    value = value.strip()
    m = re.fullmatch(r"oklch\(([\d.]+) ([\d.]+) ([\d.]+)(?: / ([\d.]+%?))?\)", value)
    if not m or m.group(4) is None:
        return to_hex(value)
    alpha = float(m.group(4)[:-1]) / 100 if m.group(4).endswith("%") else float(m.group(4))
    return to_hex("oklch(%s %s %s)" % m.groups()[:3]) + ("%02x" % round(alpha * 255) if alpha < 1 else "")


def write_palette_data(palettes: str, path: Path) -> None:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import build_theme
    roles = role_list(palettes)
    parsed = build_theme.parse_palettes(palettes)

    def full(colors: dict) -> dict:
        missing = [r for r in roles if r not in colors]
        if missing:
            raise ValueError("palette lacks roles: %s" % missing)
        return {r: full_hex(colors[r]) for r in roles}

    def artwork(theme_id: str) -> bool:
        m = re.search(r'id: "%s",.*?(?=export const|\Z)' % re.escape(theme_id), palettes, re.S)
        return bool(m and "sidebarArtwork: true" in m.group(0))

    built_in = []
    for theme_id, theme in parsed.items():
        if theme_id.startswith("standard-"):
            continue
        entry = {"id": theme_id, "label": theme["label"], "appearance": theme["appearance"], "colors": full(theme["colors"])}
        if theme["variants"]:
            entry["variants"] = {mode: full(colors) for mode, colors in theme["variants"].items()}
        entry["sidebarArtwork"] = artwork(theme_id)
        built_in.append(entry)
    standard = {mode: full(parsed["standard-" + mode]["colors"]) for mode in ("light", "dark")}
    out = [
        "// Generated by tools/gen_theme_previews.py --palette-data from packages/shared/src/themePalettes.ts.",
        "// Do not edit by hand.",
        "",
        "export const THEME_COLOR_ROLES = " + json.dumps(roles) + " as const;",
        "export type ThemeColorRole = (typeof THEME_COLOR_ROLES)[number];",
        "export type ThemeColors = Record<ThemeColorRole, string>;",
        "export interface PaletteTheme { id: string; label: string; appearance: \"light\" | \"dark\"; colors: ThemeColors; variants?: { light?: ThemeColors; dark?: ThemeColors }; sidebarArtwork: boolean }",
        "",
        "/** The standard T3 Code palette (T3_CODE_LIGHT_THEME_COLORS, T3_CODE_DARK_THEME_COLORS with the dark canvas index.css paints). */",
        "export const STANDARD_COLORS: { light: ThemeColors; dark: ThemeColors } = " + json.dumps({"light": standard["light"], "dark": {**standard["dark"], "canvas": "#000000"}}, indent=2) + ";",
        "",
        "export const BUILT_IN_PALETTES: PaletteTheme[] = " + json.dumps(built_in, indent=2) + ";",
        "",
    ]
    path.write_text("\n".join(out))


def main():
    palettes = (SRC / "themePalettes.ts").read_text()
    if PALETTE_DATA is not None:
        write_palette_data(palettes, PALETTE_DATA)
    cards = []
    for m in re.finditer(r'export const (\w+_THEME): ThemeDefinition = \{\s*id: "([^"]+)",\s*label: "([^"]+)",\s*appearance: "(light|dark)"', palettes):
        base = m.group(0)
        start = m.start()
        body = block(palettes, start)
        appearance = m.group(4)
        colors = block(body, body.index("colors:"))
        previews = [{"mode": appearance, "colors": roles_of(colors)}]
        if "variants:" in body:
            variants = block(body, body.index("variants:"))
            for vm in re.finditer(r"\b(light|dark):\s*\{", variants):
                if vm.group(1) == appearance:
                    continue
                previews.append({"mode": vm.group(1), "colors": roles_of(block(variants, vm.start()))})
        previews.sort(key=lambda p: 0 if p["mode"] == "light" else 1)
        cards.append({"id": m.group(2), "label": m.group(3), "previews": previews})
    # ThemePreviewCircles.tsx STANDARD_THEME_PREVIEW_COLORS: the standard T3 Code card is not the app palette; four roles are
    # fixed there and canvas, accent and messageAction come from packages/shared/src/themePreview.ts.
    shared = (SRC / "themePreview.ts").read_text()
    fixed = {
        "light": {"sidebar": "#fafafa", "surface": "#ffffff", "accentSurface": "#f4f4f5", "messageSurface": "#e4e4e7"},
        "dark": {"sidebar": "#0f0f10", "surface": "#121212", "accentSurface": "#27272a", "messageSurface": "#27272a"},
    }
    std = {}
    for mode in ("light", "dark"):
        body = block(shared, shared.index("%s: {" % mode, shared.index("STANDARD_THEME_PREVIEW_COLORS")))
        found = dict(re.findall(r'(\w+):\s*"([^"]+)"', body))
        std[mode] = {**fixed[mode], "canvas": found["canvas"], "accent": found["accent"], "messageAction": found["messageAction"]}
        std[mode] = {role: std[mode][role] for role in ROLES if role in std[mode]}
        std[mode]["messageAction"] = found["messageAction"]
    default = {"id": "default", "label": "R3 Code", "previews": [{"mode": m, "colors": std[m]} for m in ("light", "dark")]}
    print("// Generated by tools/gen_theme_previews.py from packages/shared/src/themePalettes.ts.")
    print("// Do not edit by hand.")
    print()
    print("export type ThemeAppearance = \"light\" | \"dark\";")
    print("export interface ThemePreviewColors { sidebar: string; canvas: string; surface: string; accentSurface: string; accent: string; messageSurface: string; messageAction: string }")
    print("export interface ThemeCard { id: string; label: string; previews: { mode: ThemeAppearance; colors: ThemePreviewColors }[] }")
    print()
    print("export const THEME_CARDS: ThemeCard[] = " + json.dumps([default] + cards, indent=2) + ";")
    sys.stderr.write("themes=%d\n" % (len(cards) + 1))


if __name__ == "__main__":
    main()
