#!/usr/bin/env python3
"""Convert cargo-about JSON into portable notices for the macOS native host.

Run cargo-about against nsh-gpui-host for aarch64-apple-darwin with its locked
dependencies first. Review cargo-about diagnostics before shipping the output.
Local registry paths and other build-machine metadata are deliberately omitted.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def convert(report: dict) -> dict:
    licenses = report["licenses"]
    texts = []
    by_crate: dict[str, list[int]] = {}
    for item in licenses:
        if not isinstance(item.get("text"), str) or not item["text"].strip():
            raise ValueError("A native dependency license has no text")
        index = len(texts)
        texts.append(item["text"])
        for use in item["used_by"]:
            by_crate.setdefault(use["crate"]["id"], []).append(index)
    packages = []
    seen: set[tuple[str, str]] = set()
    for item in report["crates"]:
        package = item["package"]
        name, version = package["name"], package["version"]
        key = (name, version)
        if key in seen:
            raise ValueError(f"Duplicate native dependency: {name} {version}")
        seen.add(key)
        references = by_crate.get(package["id"])
        if not references:
            raise ValueError(f"No license text for native dependency: {name} {version}")
        url = package.get("repository")
        if not isinstance(url, str) or not url.startswith(("https://", "http://")):
            url = None
        packages.append({"name": name, "version": version, "license": item["license"], "sourceUrl": url, "texts": references})
    packages.sort(key=lambda item: (item["name"].lower(), item["version"]))
    return {"texts": texts, "packages": packages}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    data = convert(json.loads(args.input.read_text()))
    args.output.write_text(
        "// Generated by tools/generate_native_licenses.py from cargo-about for aarch64-apple-darwin.\n"
        "// Review cargo-about diagnostics and regenerate when the native host dependencies change.\n"
        "export const nativeLicenseData: { texts: string[]; packages: { name: string; version: string; license: string; sourceUrl: string | null; texts: number[] }[] } = "
        + json.dumps(data, ensure_ascii=True, separators=(",", ":")) + ";\n"
    )
    print(f"Generated {len(data['packages'])} native dependency notices")


if __name__ == "__main__":
    main()
